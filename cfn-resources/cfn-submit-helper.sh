#!/usr/bin/env bash

# cfn-submit-helper.sh
#
# Builds and submits one or more resources to the CloudFormation private
# registry. Before the role stack is created, the tags required by the
# Cloud Tag Policy are injected into the resource-role.yaml template.
#
# Usage:
# ./cfn-submit-helper.sh <resource-folder> [<resource-folder> ...]
#
# There are some options.
#
# BUILD_ONLY=true|false
# SUBMIT_ONLY=true|false
# CFN_SUBMIT_LOG_LEVEL=logrus valid string loglevel
#
# Example with DEBUG logging enabled for a set of resources:
# CFN_SUBMIT_LOG_LEVEL=debug ./cfn-submit-helper.sh project database-user project-ip-access-list cluster network-peering
#
set -eo
# shellcheck source=/dev/null
. ./cfn-submit-helper.config
# shellcheck source=/dev/null
source "$(dirname "$0")/tag-policy.sh"
env | grep CFN_SUBMIT_

_DRY_RUN=${DRY_RUN:-false}
_BUILD_ONLY=${BUILD_ONLY:-false}
_SUBMIT_ONLY=${SUBMIT_ONLY:-false}

[[ "${_DRY_RUN}" == "true" ]] && echo "*************** DRY_RUN mode enabled **************"

# One or more resource folders are required, for example:
# ./cfn-submit-helper.sh project database-user
resources="$*"
if [ -z "${resources}" ]; then
	echo "Usage: $(basename "$0") <resource-folder> [<resource-folder> ...]" >&2
	exit 1
fi
echo "$(basename "$0") running for the following resources: ${resources}"

echo "Step 1/2: Building"
if [[ "${_SUBMIT_ONLY}" == "true" ]]; then
	echo "SUBMIT_ONLY, skipping build."
else
	for resource in ${resources}; do
		[[ "${_DRY_RUN}" == "true" ]] && echo "[dry-run] would have run make on:${resource}" && continue
		echo "Working on resource:${resource}"
		cd "${resource}"
		echo "resource: ${resource}"

		if [[ "${CFN_SUBMIT_LOG_LEVEL}" == "debug" ]]; then
			make debug
		else
			make
		fi
		# CFN Autogenerated role doesn't work cof AWS CloudFormation test-type command, so replacing with proper role.
		curl https://mdb-cfn-publish.s3.amazonaws.com/resource-role.yaml >resource-role.yaml
		cd -
	done
fi
if [[ "${_BUILD_ONLY}" == "true" ]]; then
	echo "BUILD_ONLY true, skipping submit to CloudFormation"
	exit 0
fi
echo "Step 2/2: Submit resource type to CloudFormation Private Registry"
for resource in ${resources}; do
	echo "Working on resource:${resource}"
	[[ "${_DRY_RUN}" == "true" ]] && echo "[dry-run] would have run 'cfn submit' on:${resource}" && continue
	cd "${resource}"
	echo "resource: ${resource}"

	echo "Deleting role stack if present"
	roleStack="mongodb-atlas-${resource//-/}-role-stack"
	command="aws cloudformation update-termination-protection --no-enable-termination-protection --stack-name ${roleStack}"
	echo "${command}"
	${command} || true
	command="aws cloudformation delete-stack --stack-name ${roleStack}"
	echo "${command}"
	${command} || true
	command=" aws cloudformation wait stack-delete-complete --stack-name ${roleStack}"
	echo "${command}"
	${command}

	echo "Submitting to CloudFormation with flags: ${CFN_SUBMIT_CFN_FLAGS[*]}"
	require_tag_policy_vars
	# Re-add the Cloud Tag Policy tags missing from the S3 role template, right before
	# cfn submit creates the role stack (also covers SUBMIT_ONLY runs). Skipped when the
	# file is already tagged, so repeated runs cannot add a duplicate Tags key.
	if ! grep -q 'Key: mongodb-owner' resource-role.yaml; then
		awk -v owner="${MONGODB_TAG_OWNER}" -v tagEnv="${MONGODB_TAG_ENV}" '/^      Path: "\/"$/ { print; print "      Tags:"; print "        - Key: mongodb-owner"; print "          Value: " owner; print "        - Key: mongodb-env"; print "          Value: " tagEnv; next } { print }' resource-role.yaml >resource-role.yaml.tmp && mv resource-role.yaml.tmp resource-role.yaml
		if ! grep -q 'Key: mongodb-owner' resource-role.yaml; then
			echo "Failed to inject tags into resource-role.yaml: the Path anchor was not found" >&2
			exit 1
		fi
	fi
	# ensure error is thrown if registration to private registry fails
	cfn submit "${CFN_SUBMIT_CFN_FLAGS[@]}"
	cd -
done
